import { describe, expect, it } from 'vitest'
import { dateJaponaise } from '../src/content/date'

describe('dateJaponaise', () => {
  it.each([
    ['2026-11-20', '{十一月|じゅういちがつ}{二十日|はつか}・{金曜日|きんようび}'],
    ['2026-04-01', '{四月|しがつ}{一日|ついたち}・{水曜日|すいようび}'],
    ['2026-09-14', '{九月|くがつ}{十四日|じゅうよっか}・{月曜日|げつようび}'],
    ['2026-07-17', '{七月|しちがつ}{十七日|じゅうしちにち}・{金曜日|きんようび}'],
    ['2026-12-31', '{十二月|じゅうにがつ}{三十一日|さんじゅういちにち}・{木曜日|もくようび}'],
    ['2026-01-24', '{一月|いちがつ}{二十四日|にじゅうよっか}・{土曜日|どようび}'],
  ])('%s', (jour, attendu) => {
    expect(dateJaponaise(new Date(`${jour}T12:00:00`))).toBe(attendu)
  })
})
